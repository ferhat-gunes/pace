import { fulfillFeatureRequest } from './browser-feature-contracts.mjs';
import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { chromium } from 'playwright';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined), headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(8000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto((process.env.PACE_BASE_URL || 'http://localhost:5173') + '/?demo=1&noworker=1');
  await page.locator('#view-today').waitFor();
  await page.getByRole('button', { name: 'Yeni alışkanlık ekle', exact: true }).filter({ visible: true }).first().click();
  await page.locator('#habit-name').fill('Ondalık yaşam döngüsü');
  await page.getByRole('button', { name: 'Miktar / Süre', exact: true }).click();
  await page.locator('#habit-target').fill('0,25');
  await page.locator('#habit-unit').fill('km');
  await page.locator('#habit-schedule').selectOption('weekdays');
  for (const day of ['Sal', 'Per', 'Cum']) await page.locator('#weekday-picker').getByLabel(day, { exact: true }).uncheck();
  await page.locator('.advanced-rules summary').click();
  await page.getByLabel('Hedefi zamanla artır', { exact: true }).check();
  await page.locator('#progressive-step').fill('0,25');
  await page.locator('#progressive-cap').fill('2');
  await page.getByLabel('Eksik miktarı sonraki planlı güne taşı', { exact: true }).check();
  await page.locator('#debt-cap').fill('1');
  assert.match(await page.getByRole('region', { name: 'Plan özeti' }).innerText(), /0,25 km/);
  await page.getByRole('button', { name: 'Alışkanlığı Kaydet', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  await page.locator('.mobile-nav [data-view="habits"]').click();
  let row = page.locator('#all-habits-list .habit-row').filter({ hasText: 'Ondalık yaşam döngüsü' });
  await row.waitFor();
  assert.match(await row.innerText(), /0,25 km/);
  await row.getByRole('button', { name: 'Ondalık yaşam döngüsü alışkanlığını düzenle', exact: true }).click();
  assert.equal(await page.locator('#habit-target').inputValue(), '0.25');
  assert.equal(await page.locator('#habit-schedule').inputValue(), 'weekdays');
  assert.equal(await page.getByLabel('Hedefi zamanla artır', { exact: true }).isChecked(), true);
  await page.locator('#habit-target').fill('0,5');
  await page.getByRole('button', { name: 'Değişiklikleri Kaydet', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'detached' });
  await row.getByRole('button', { name: 'Ondalık yaşam döngüsü alışkanlığını duraklat', exact: true }).click();
  await row.getByRole('button', { name: 'Ondalık yaşam döngüsü alışkanlığını devam ettir', exact: true }).waitFor();
  await row.getByRole('button', { name: 'Ondalık yaşam döngüsü alışkanlığını devam ettir', exact: true }).click();
  await row.getByRole('button', { name: 'Ondalık yaşam döngüsü alışkanlığını arşivle', exact: true }).click();
  await row.getByRole('button', { name: 'Evet, Arşivle', exact: true }).click();
  await row.waitFor({ state: 'detached' });
  await page.locator('#archived-habits summary').click();
  row = page.locator('#archive-list .habit-row').filter({ hasText: 'Ondalık yaşam döngüsü' });
  await row.getByRole('button', { name: 'Ondalık yaşam döngüsü alışkanlığını arşivden çıkar', exact: true }).click();
  await page.locator('#all-habits-list .habit-row').filter({ hasText: 'Ondalık yaşam döngüsü' }).waitFor();
  const formPage = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  formPage.setDefaultTimeout(8000);
  let releaseSave;
  let attempts = 0;
  let savedHabits = [];
  await formPage.route('**/api/**', async route => {
    if(await fulfillFeatureRequest(route))return;
    const req = route.request(), path = new URL(req.url()).pathname;
    if (path === '/api/habits' && req.method() === 'GET') return route.fulfill({ json: { user: { id: 'editor-test', email: 'editor@example.test' }, habits: savedHabits, checkins: [] } });
    if (path === '/api/groups' && req.method() === 'GET') return route.fulfill({ json: { groups: [] } });
    if (path === '/api/habits' && req.method() === 'POST') {
      attempts++;
      if (attempts === 1) {
        await new Promise(resolve => { releaseSave = resolve; });
        return route.fulfill({ status: 500, json: { error: 'Deneme kaydı başarısız oldu.' } });
      }
      const habit = { ...req.postDataJSON(), id: 'saved-editor' }; savedHabits = [habit];
      return route.fulfill({ json: { habit } });
    }
    throw new Error('Unexpected API contract: ' + req.method() + ' ' + path);
  });
  await formPage.goto((process.env.PACE_BASE_URL || 'http://localhost:5173') + '/?noworker=1');
  await formPage.locator('#view-today').waitFor();
  await formPage.getByRole('button', { name: 'Yeni alışkanlık ekle', exact: true }).filter({ visible: true }).first().click();
  await formPage.locator('#habit-name').fill('Korunan form');
  await formPage.getByRole('button', { name: 'Alışkanlığı Kaydet', exact: true }).click();
  await formPage.waitForFunction(() => document.querySelector('#habit-name')?.matches(':disabled'));
  assert.equal(await formPage.getByRole('button', { name: 'Kapat', exact: true }).isDisabled(), true);
  await formPage.keyboard.press('Escape');
  assert.equal(await formPage.getByRole('dialog').isVisible(), true, 'pending form cannot close by Escape');
  await formPage.locator('.modal-overlay').click({ position: { x: 5, y: 5 } });
  assert.equal(await formPage.getByRole('dialog').isVisible(), true, 'pending form cannot close by backdrop');
  releaseSave();
  await formPage.getByRole('alert').filter({ hasText: 'Deneme kaydı başarısız' }).waitFor();
  assert.equal(await formPage.locator('#habit-name').inputValue(), 'Korunan form');
  await formPage.getByRole('button', { name: 'Alışkanlığı Kaydet', exact: true }).click();
  await formPage.getByRole('dialog').waitFor({ state: 'detached' });
  assert.equal(attempts, 2);
  await formPage.getByRole('button', { name: 'Yeni alışkanlık ekle', exact: true }).filter({ visible: true }).first().click();
  await formPage.locator('#habit-name').fill('   ');
  await formPage.getByRole('button', { name: 'Alışkanlığı Kaydet', exact: true }).click();
  await formPage.getByRole('alert').filter({ hasText: 'Alışkanlık adı' }).waitFor();
  assert.equal(await formPage.locator('#habit-name').getAttribute('aria-invalid'), 'true');
  assert.equal(attempts, 2, 'invalid name must not make a request');
  await formPage.locator('#habit-name').fill('Kaybolmayan taslak');
  await formPage.keyboard.press('Escape');
  await formPage.getByText('Kaydedilmemiş değişikliklerin var.', { exact: true }).waitFor();
  await formPage.getByRole('button', { name: 'Düzenlemeye devam et', exact: true }).click();
  assert.equal(await formPage.locator('#habit-name').inputValue(), 'Kaybolmayan taslak');
  await formPage.keyboard.press('Escape');
  await formPage.getByRole('button', { name: 'Değişiklikleri bırak', exact: true }).click();
  await formPage.getByRole('dialog').waitFor({ state: 'detached' });
  await formPage.close();
  assert.deepEqual(errors, []);
  console.log('PASS: decimal target, weekdays, progression, carryover, edit, pause, resume, archive, restore, pending locks, failure/retry, dirty confirmation, accessible validation');
} finally { await browser.close(); }
